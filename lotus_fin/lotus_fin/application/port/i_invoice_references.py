"""Application-owned reference contract; infrastructure implements it."""
from typing import Protocol


class IInvoiceReferences(Protocol):
    def sign_selection_v2(self, context, doc_id, record_version, ttl_seconds=None,
                          query_fingerprint=None) -> str: ...
    def verify_selection_v2(self, token, context): ...
    def sign_cursor_v2(self, context, query_fingerprint, last_id, upper_id,
                       page_index, page_size, ttl_seconds=None) -> str: ...
    def verify_cursor_v2(self, token, context): ...
